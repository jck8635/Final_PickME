-- 접속 계정: pickme_user
-- 대상 스키마: public


-- 1. 회원
CREATE TABLE "user" (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    nickname VARCHAR(80) NOT NULL,

    CONSTRAINT uq_user_email UNIQUE (email),
    CONSTRAINT uq_user_nickname UNIQUE (nickname)
);


-- 2. 고민·결정 기록
CREATE TABLE decision (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL,

    title VARCHAR(200) NOT NULL,
    question VARCHAR(10000) NOT NULL,
    result_json JSONB,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    category VARCHAR(80) NOT NULL DEFAULT '일반',
    is_bookmarked BOOLEAN NOT NULL DEFAULT FALSE,

    actual_choice VARCHAR(10000),
    satisfaction_score INTEGER,
    retrospective_note VARCHAR(10000),

    CONSTRAINT fk_decision_user
        FOREIGN KEY (user_id)
        REFERENCES "user"(id)
        ON DELETE CASCADE,

    CONSTRAINT ck_decision_satisfaction
        CHECK (
            satisfaction_score IS NULL
            OR satisfaction_score BETWEEN 1 AND 5
        )
);

CREATE INDEX ix_decision_user_id
    ON decision(user_id);

CREATE INDEX ix_decision_category
    ON decision(category);


-- 3. 커뮤니티 게시글
CREATE TABLE post (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    user_id INTEGER NOT NULL,

    title VARCHAR(200) NOT NULL,
    content VARCHAR(10000) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    category VARCHAR(40) NOT NULL DEFAULT '기타',
    ai_recommendation VARCHAR(120),

    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_post_user
        FOREIGN KEY (user_id)
        REFERENCES "user"(id)
        ON DELETE CASCADE
);

CREATE INDEX ix_post_user_id
    ON post(user_id);


-- 4. 게시글 투표 선택지
CREATE TABLE post_options (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    post_id INTEGER NOT NULL,
    name VARCHAR(120) NOT NULL,

    CONSTRAINT fk_post_options_post
        FOREIGN KEY (post_id)
        REFERENCES post(id)
        ON DELETE CASCADE
);


-- 5. 댓글
CREATE TABLE comment (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    post_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,

    content VARCHAR(10000) NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_comment_post
        FOREIGN KEY (post_id)
        REFERENCES post(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_comment_user
        FOREIGN KEY (user_id)
        REFERENCES "user"(id)
        ON DELETE CASCADE
);

CREATE INDEX ix_comment_post_id
    ON comment(post_id);

CREATE INDEX ix_comment_user_id
    ON comment(user_id);


-- 6. 공감
CREATE TABLE community_likes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    post_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_community_likes_post
        FOREIGN KEY (post_id)
        REFERENCES post(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_community_likes_user
        FOREIGN KEY (user_id)
        REFERENCES "user"(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_community_like_post_user
        UNIQUE (post_id, user_id)
);


-- 7. 투표
CREATE TABLE community_votes (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    post_id INTEGER NOT NULL,
    option_id INTEGER NOT NULL,
    user_id INTEGER NOT NULL,

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_community_votes_post
        FOREIGN KEY (post_id)
        REFERENCES post(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_community_votes_option
        FOREIGN KEY (option_id)
        REFERENCES post_options(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_community_votes_user
        FOREIGN KEY (user_id)
        REFERENCES "user"(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_community_vote_post_user
        UNIQUE (post_id, user_id)
);


-- 8. 게시글 신고
CREATE TABLE post_reports (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    post_id INTEGER NOT NULL,
    reporter_id INTEGER NOT NULL,

    reason VARCHAR(500) NOT NULL,

    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',

    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_post_reports_post
        FOREIGN KEY (post_id)
        REFERENCES post(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_post_reports_reporter
        FOREIGN KEY (reporter_id)
        REFERENCES "user"(id)
        ON DELETE CASCADE,

    CONSTRAINT uq_post_reports_post_reporter
        UNIQUE (post_id, reporter_id),

    CONSTRAINT ck_post_reports_status
        CHECK (status IN ('PENDING', 'REJECTED'))
);
